// Command gen writes the fault injection wrappers of package faultinject:
// one C wrapper for every rcl, rcl_action, rmw and rcutils function that
// rclgo calls and that returns an error code or a pointer (NULL on failure),
// and the linker flags that route rclgo's calls through them.
//
// Usage (from package faultinject, with ROS sourced): go generate
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io/fs"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// headers declare every function rclgo calls.
var headers = []string{
	"rcl/rcl.h",
	"rcl/graph.h",
	"rcl/expand_topic_name.h",
	"rcl/logging.h",
	"rcl/logging_rosout.h",
	"rcl/arguments.h",
	"rcl_action/rcl_action.h",
	"rcl_action/graph.h",
	"rmw/rmw.h",
	"rmw/serialized_message.h",
	"rmw/topic_endpoint_info_array.h",
	"rcutils/types.h",
	"rcutils/error_handling.h",
	"rcutils/logging.h",
	"rcl_yaml_param_parser/parser.h",
}

// includePackages are the include directories of the headers: the ones rclgo
// itself builds with (rclgoROSIncludes in pkg/gogen, see pkg/rclgo/flags.gen.go),
// so that the output does not depend on what else is installed.
var includePackages = []string{
	"action_msgs",
	"builtin_interfaces",
	"rcl",
	"rcutils",
	"rcl_action",
	"rcl_yaml_param_parser",
	"rmw",
	"rosidl_dynamic_typesupport",
	"rosidl_runtime_c",
	"rosidl_typesupport_interface",
	"service_msgs",
	"type_description_interfaces",
	"unique_identifier_msgs",
}

// skip lists functions that must not fail: the wrappers report injected
// errors with them.
var skip = map[string]bool{
	"rcutils_set_error_state": true,
	"rcutils_reset_error":     true,
}

var (
	identRe = regexp.MustCompile(`\b(?:rcl|rmw|rcutils|rcl_action)_[a-z0-9_]+\b`)
	protoRe = regexp.MustCompile(`(?:^|[\s;}])((?:rcl|rmw|rcutils)_ret_t)\s+([a-z0-9_]+)\s*\(([^()]*)\)\s*;`)
	// Functions returning a pointer fail by returning NULL.
	ptrProtoRe = regexp.MustCompile(`(?:^|[\s;})])((?:const\s+)?[a-z_][a-z0-9_]*\s*\*+)\s*([a-z0-9_]+)\s*\(([^()]*)\)\s*;`)
	nameRe     = regexp.MustCompile(`([A-Za-z_][A-Za-z0-9_]*)\s*(?:\[[^\]]*\])?\s*$`)
)

func main() {
	root := flag.String("root", "/opt/ros/"+os.Getenv("ROS_DISTRO"), "ROS installation whose headers declare the functions")
	src := flag.String("src", "../..", "rclgo package directory to scan for calls")
	out := flag.String("out", ".", "directory to write the wrappers to")
	flag.Parse()

	var includeDirs []string
	for _, pkg := range includePackages {
		d := filepath.Join(*root, "include", pkg)
		if _, err := os.Stat(d); err != nil {
			log.Fatalf("include directory missing: %v", err)
		}
		includeDirs = append(includeDirs, d)
	}
	called := calledFunctions(*src)

	var in bytes.Buffer
	for _, h := range headers {
		fmt.Fprintf(&in, "#include <%s>\n", h)
	}
	args := []string{"-E", "-P", "-x", "c", "-"}
	for _, d := range includeDirs {
		args = append(args, "-I"+d)
	}
	cmd := exec.Command("gcc", args...)
	cmd.Stdin = &in
	cmd.Stderr = os.Stderr
	pre, err := cmd.Output()
	if err != nil {
		log.Fatalf("preprocessing the headers: %v", err)
	}
	text := strings.Join(strings.Fields(string(pre)), " ")

	type proto struct{ ret, name, params string }
	protos := map[string]proto{}
	for _, re := range []*regexp.Regexp{protoRe, ptrProtoRe} {
		for _, m := range re.FindAllStringSubmatch(text, -1) {
			if called[m[2]] && !skip[m[2]] {
				protos[m[2]] = proto{m[1], m[2], strings.TrimSpace(m[3])}
			}
		}
	}
	names := make([]string, 0, len(protos))
	for n := range protos {
		names = append(names, n)
	}
	sort.Strings(names)

	var c bytes.Buffer
	c.WriteString("// Code generated by gen/main.go. DO NOT EDIT.\n\n#include \"faultinject.h\"\n")
	for _, h := range headers {
		fmt.Fprintf(&c, "#include <%s>\n", h)
	}
	for _, n := range names {
		p := protos[n]
		var argNames []string
		if p.params != "void" && p.params != "" {
			for _, param := range strings.Split(p.params, ",") {
				m := nameRe.FindStringSubmatch(param)
				if m == nil {
					log.Fatalf("%s: cannot find the name of parameter %q", n, param)
				}
				argNames = append(argNames, m[1])
			}
		}
		fmt.Fprintf(&c, "\n%s __real_%s(%s);\n%s __wrap_%s(%s)\n{\n", p.ret, n, p.params, p.ret, n, p.params)
		failValue := "(" + p.ret + ")ret"
		if strings.HasSuffix(p.ret, "*") {
			failValue = "NULL"
		}
		if strings.HasSuffix(n, "_fini") && !strings.HasSuffix(p.ret, "*") {
			// rcl's fini functions release everything even when they fail
			// (rcl_timer_fini, for example, still removes its clock jump
			// callback and frees the timer), so a failing fini is modelled
			// as the real call followed by the error.
			fmt.Fprintf(&c, "  %s real = __real_%s(%s);\n", p.ret, n, strings.Join(argNames, ", "))
			fmt.Fprintf(&c, "  int ret;\n  if (rclgo_fi_should_fail(\"%s\", &ret)) {\n    return %s;\n  }\n  return real;\n}\n", n, failValue)
			continue
		}
		fmt.Fprintf(&c, "  int ret;\n  if (rclgo_fi_should_fail(\"%s\", &ret)) {\n    (void)ret;\n    return %s;\n  }\n", n, failValue)
		fmt.Fprintf(&c, "  return __real_%s(%s);\n}\n", n, strings.Join(argNames, ", "))
	}

	var g bytes.Buffer
	g.WriteString("// Code generated by gen/main.go. DO NOT EDIT.\n\npackage faultinject\n\n/*\n")
	for _, d := range includeDirs {
		fmt.Fprintf(&g, "#cgo CFLAGS: -I%s\n", d)
	}
	fmt.Fprintf(&g, "#cgo LDFLAGS: -L%s/lib -Wl,-rpath=%s/lib -lrcl -lrcl_action -lrmw -lrcutils -lrcl_yaml_param_parser\n", *root, *root)
	for _, n := range names {
		fmt.Fprintf(&g, "#cgo LDFLAGS: -Wl,--wrap=%s\n", n)
	}
	g.WriteString("*/\nimport \"C\"\n\n// Functions are the functions whose calls can be made to fail.\nvar Functions = []string{\n")
	for _, n := range names {
		fmt.Fprintf(&g, "\t%q,\n", n)
	}
	g.WriteString("}\n")
	goSrc, err := format.Source(g.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(*out, "wrappers.gen.c"), c.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(*out, "wrappers.gen.go"), goSrc, 0o644); err != nil {
		log.Fatal(err)
	}
	var missing []string
	for n := range called {
		if _, ok := protos[n]; !ok {
			missing = append(missing, n)
		}
	}
	sort.Strings(missing)
	fmt.Fprintf(os.Stderr, "%d functions wrapped; %d called identifiers not wrapped (no error code, macros or types):\n  %s\n",
		len(names), len(missing), strings.Join(missing, " "))
}

// calledFunctions returns the rcl, rmw and rcutils identifiers in the
// non-test Go files (including their C preambles) under dir, except this
// package.
func calledFunctions(dir string) map[string]bool {
	called := map[string]bool{}
	err := filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() && d.Name() == "faultinject" {
			return filepath.SkipDir
		}
		if d.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		b, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		for _, id := range identRe.FindAllString(string(b), -1) {
			called[id] = true
		}
		return nil
	})
	if err != nil {
		log.Fatal(err)
	}
	return called
}
